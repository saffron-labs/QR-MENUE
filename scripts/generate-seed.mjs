// Builds supabase/seed.sql from the prototype's menu (scripts/chackos-menu.source.json).
// Run: node scripts/generate-seed.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const items = JSON.parse(readFileSync(new URL("./chackos-menu.source.json", import.meta.url), "utf8"));

// Deterministic UUIDs so re-running the seed never changes ids.
const uuid = (key) => {
  const h = createHash("sha1").update(`chackos:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;
const paise = (rupees) => Math.round(rupees * 100);

const restaurantId = uuid("restaurant");
const categories = [
  ["mandi", "Kuzhi Mandi"],
  ["mandi-combos", "Grill Mandi / Biryani"],
  ["shawarma", "Shawarma"],
  ["grills", "Alfaham & Shawaya"],
  ["curry-breads", "Curry & Breads"],
  ["biryani-rice", "Biryani & Rice"],
  ["sides-dips", "Sides & Dips"],
  ["drinks", "Water & Cold Drinks"],
];
const DIP_CATEGORIES = new Set(["mandi", "mandi-combos", "shawarma", "grills", "curry-breads"]);
const EXTRA_DIPS = ["Garlic Mayo (Toum)", "Tomato Chutney (Sahawiq)", "Mint Chutney", "Shawaya Masala Dip"];

const out = [];
out.push("-- GENERATED by scripts/generate-seed.mjs. Do not edit by hand.");
out.push("begin;");
out.push(
  `insert into restaurants (id, slug, name, tagline, address, phone, hours, gst_rate_bp) values (${q(restaurantId)}, 'chackos', 'Chackos Dining', 'Kerala & Malabar-Arabian cuisine, casually served', 'Bhutanese Colony, next to Jazzy Properties (near LPU)', '98145 88805', '12 PM - 11 PM', 500) on conflict (id) do nothing;`,
);

categories.forEach(([slug, name], i) =>
  out.push(
    `insert into categories (id, restaurant_id, slug, name, sort_order) values (${q(uuid("cat:" + slug))}, ${q(restaurantId)}, ${q(slug)}, ${q(name)}, ${i}) on conflict (id) do nothing;`,
  ),
);

items.forEach((it, i) => {
  const id = uuid("item:" + it.id);
  // The prototype's local banner is a screenshot of the restaurant's website, not a dish photo.
  const image = it.image.includes("chackos-banner") ? null : it.image.startsWith("assets/") ? "/" + it.image.replace("assets/", "menu/") : it.image;
  out.push(
    `insert into menu_items (id, restaurant_id, category_id, name, description, price_paise, image_url, prep_time, tags, is_available, sort_order) values (${q(id)}, ${q(restaurantId)}, ${q(uuid("cat:" + it.category))}, ${q(it.name)}, ${q(it.description)}, ${paise(it.price)}, ${q(image)}, ${q(it.prepTime)}, ${arr(it.tags ?? [])}, ${it.isAvailable !== false}, ${i}) on conflict (id) do nothing;`,
  );

  const groups = [];
  if (it.isMandiBiryaniChoice) {
    groups.push({ key: "rice", name: "Choose your rice", min: 1, max: 1, options: [["Smoky Mandi Rice", 0, true], ["Dum Biryani Rice", 0, false]] });
  }
  if (it.isGrillBreadChoice) {
    groups.push({ key: "bread", name: "Choose your bread", min: 1, max: 1, options: [["Rumali Roti (free)", 0, true], ["Kerala Porotta", 500, false]] });
  }
  if (it.allowSpiceChoice && it.spiciness && it.spiciness !== "None") {
    const def = it.spiciness === "Hot" ? "Hot" : it.spiciness === "Medium" ? "Medium" : "Mild";
    groups.push({ key: "spice", name: "Spice level", min: 1, max: 1, options: ["Mild", "Medium", "Hot"].map((n) => [n, 0, n === def]) });
  }
  if (DIP_CATEGORIES.has(it.category)) {
    groups.push({ key: "dips", name: "Extra dips", min: 0, max: EXTRA_DIPS.length, options: EXTRA_DIPS.map((n) => [n, 2000, false]) });
  }

  groups.forEach((g, gi) => {
    const gid = uuid(`group:${it.id}:${g.key}`);
    out.push(
      `insert into modifier_groups (id, menu_item_id, name, min_select, max_select, sort_order) values (${q(gid)}, ${q(id)}, ${q(g.name)}, ${g.min}, ${g.max}, ${gi}) on conflict (id) do nothing;`,
    );
    g.options.forEach(([name, delta, isDefault], oi) =>
      out.push(
        `insert into modifier_options (id, group_id, name, price_delta_paise, is_default, sort_order) values (${q(uuid(`opt:${it.id}:${g.key}:${name}`))}, ${q(gid)}, ${q(name)}, ${delta}, ${isDefault}, ${oi}) on conflict (id) do nothing;`,
      ),
    );
  });
});

for (let n = 1; n <= 14; n++) {
  const label = `T-${String(n).padStart(2, "0")}`;
  out.push(
    `insert into dining_tables (id, restaurant_id, label) values (${q(uuid("table:" + label))}, ${q(restaurantId)}, ${q(label)}) on conflict (id) do nothing;`,
  );
}
out.push("commit;");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`seed.sql: ${items.length} items, ${out.length} statements`);
